function escape(re: string): string {
  return re.replace(/[.*+?^${}()|[\]\\/#]/g, "\\$&");
}

// Word boundaries that respect symbols in names like c++, c#, .net, node.js.
const MATCHERS: [string, RegExp][] = Object.entries(SKILLS).map(([skill, aliases]) => [
  skill,
  new RegExp(`(?<![a-z0-9+#.])(?:${aliases.map(escape).join("|")})(?![a-z0-9+#])`, "i"),
]);

/** extractSkills returns canonical skill names found in the text, in dictionary order. */
export function extractSkills(text: string): string[] {
  return MATCHERS.filter(([, re]) => re.test(text)).map(([skill]) => skill);
}
